"""HID report layout and Windows virtual-key -> HID usage mapping."""

# Composite keyboard (report ID 1) + mouse (report ID 2).
# Keep this byte-for-byte stable: a bonded iPad caches the GATT table and report map,
# so changing it means "Forget This Device" on the iPad and pairing again.
REPORT_MAP = bytes([
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01,             # Keyboard, report ID 1
    0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x08, 0x81, 0x02,                         #   8 modifier bits
    0x95, 0x01, 0x75, 0x08, 0x81, 0x01,                         #   reserved byte
    0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
    0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00,             #   6 key slots
    0xC0,
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02,             # Mouse, report ID 2
    0x09, 0x01, 0xA1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
    0x95, 0x03, 0x75, 0x01, 0x81, 0x02,                         #   3 buttons
    0x95, 0x01, 0x75, 0x05, 0x81, 0x01,                         #   padding
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38,
    0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06,  #   X, Y, wheel (relative, -127..127)
    0xC0, 0xC0,
])

KEYBOARD_REPORT_ID = 1
MOUSE_REPORT_ID = 2

BUTTON_LEFT = 0x01
BUTTON_RIGHT = 0x02
BUTTON_MIDDLE = 0x04

_USAGE = {}
for _i in range(26):
    _USAGE[0x41 + _i] = 0x04 + _i                      # A..Z
for _i in range(9):
    _USAGE[0x31 + _i] = 0x1E + _i                      # 1..9
_USAGE[0x30] = 0x27                                    # 0
for _i in range(12):
    _USAGE[0x70 + _i] = 0x3A + _i                      # F1..F12
for _i in range(9):
    _USAGE[0x61 + _i] = 0x59 + _i                      # Numpad 1..9
_USAGE.update({
    0x0D: 0x28, 0x1B: 0x29, 0x08: 0x2A, 0x09: 0x2B, 0x20: 0x2C,  # Enter Esc Backspace Tab Space
    0xBD: 0x2D, 0xBB: 0x2E, 0xDB: 0x2F, 0xDD: 0x30, 0xDC: 0x31,  # - = [ ] \
    0xBA: 0x33, 0xDE: 0x34, 0xC0: 0x35, 0xBC: 0x36, 0xBE: 0x37,  # ; ' ` , .
    0xBF: 0x38, 0x14: 0x39,                                      # / CapsLock
    0x2C: 0x46, 0x91: 0x47, 0x13: 0x48,                          # PrintScreen ScrollLock Pause
    0x2D: 0x49, 0x24: 0x4A, 0x21: 0x4B, 0x2E: 0x4C, 0x23: 0x4D, 0x22: 0x4E,  # Ins Home PgUp Del End PgDn
    0x27: 0x4F, 0x25: 0x50, 0x28: 0x51, 0x26: 0x52,              # Right Left Down Up
    0x90: 0x53, 0x6F: 0x54, 0x6A: 0x55, 0x6D: 0x56, 0x6B: 0x57,  # NumLock / * - +
    0x60: 0x62, 0x6E: 0x63, 0xE2: 0x64, 0x5D: 0x65,              # Numpad 0 . , non-US \ , Menu
})

VK_LSHIFT, VK_RSHIFT = 0xA0, 0xA1
VK_LCONTROL, VK_RCONTROL = 0xA2, 0xA3
VK_LMENU, VK_RMENU = 0xA4, 0xA5
VK_LWIN, VK_RWIN = 0x5B, 0x5C
VK_SHIFT, VK_CONTROL, VK_MENU = 0x10, 0x11, 0x12

CTRL_KEYS = {VK_LCONTROL, VK_RCONTROL, VK_CONTROL}
ALT_KEYS = {VK_LMENU, VK_RMENU, VK_MENU}
SHIFT_KEYS = {VK_LSHIFT, VK_RSHIFT, VK_SHIFT}
WIN_KEYS = {VK_LWIN, VK_RWIN}


def usage(vk, extended):
    """HID keyboard usage for a Windows virtual key, or 0 if unmapped."""
    if vk == 0x0D and extended:
        return 0x58  # keypad Enter
    return _USAGE.get(vk, 0)


def modifier_bit(vk, ctrl_as_cmd):
    """Modifier bit in the keyboard report (Win = Command on iPadOS, Alt = Option)."""
    if vk in (VK_LCONTROL, VK_CONTROL):
        return 0x08 if ctrl_as_cmd else 0x01
    if vk == VK_RCONTROL:
        return 0x80 if ctrl_as_cmd else 0x10
    if vk in (VK_LSHIFT, VK_SHIFT):
        return 0x02
    if vk == VK_RSHIFT:
        return 0x20
    if vk in (VK_LMENU, VK_MENU):
        return 0x04
    if vk == VK_RMENU:
        return 0x40
    if vk == VK_LWIN:
        return 0x01 if ctrl_as_cmd else 0x08
    if vk == VK_RWIN:
        return 0x10 if ctrl_as_cmd else 0x80
    return 0
