def set_dpi_aware():
    """Work in physical pixels so hook coordinates, SetCursorPos and monitor rects agree."""
    try:
        ctypes.WinDLL("shcore").SetProcessDpiAwareness(2)  # per-monitor aware
    except (OSError, AttributeError):
        user32.SetProcessDPIAware()


def cursor_pos():
    p = wintypes.POINT()
    user32.GetCursorPos(ctypes.byref(p))
    return p.x, p.y


def monitor_rects():
    """Return every monitor as (left, top, right, bottom) with right/bottom exclusive."""
    rects = []

    def _collect(hmon, hdc, rect, data):
        r = rect.contents
        rects.append((r.left, r.top, r.right, r.bottom))
        return True

    user32.EnumDisplayMonitors(None, None, MONITORENUMPROC(_collect), 0)
    return rects


def message_box(text, title="iPad Bridge", flags=MB_ICONINFORMATION):
    user32.MessageBoxW(None, text, title, flags)
